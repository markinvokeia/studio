/**
 * Returns deduplicated permission codes for a given role name.
 * Returns empty array for unknown roles.
 */
export function getDefaultPermissionsForRole(roleName: string): string[] {
  const key = Object.keys(DEFAULT_ROLE_PERMISSIONS).find(
    (k) => k.toLowerCase() === roleName.toLowerCase()
  );
  if (!key) return [];
  return Array.from(new Set(DEFAULT_ROLE_PERMISSIONS[key]));
}

